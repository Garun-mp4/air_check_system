"""Generate the firmware resource plan from the shared hardware contract."""
import argparse
import json
from pathlib import Path


def render(config):
    sensors = {sensor['id']: sensor for sensor in config['sensors']}
    constants = {
        'sda': config['sensor_bus']['sda'], 'scl': config['sensor_bus']['scl'],
        'i2c_hz': config['sensor_bus']['frequency_hz'],
        **config['outputs'], **config['inputs'],
        **{f'sd_{key}': config['sd'][key] for key in ('sck', 'miso', 'mosi', 'cs')},
        **{f'indoor_uart_{key}': sensors['indoor_particles'][key] for key in ('rx', 'tx')},
        **{f'outdoor_uart_{key}': sensors['outdoor_particles'][key] for key in ('rx', 'tx')},
        **config['limits'],
        'sensor_stale_ms': min(sensor['stale_ms'] for sensor in config['sensors']),
    }
    lines = ['// Generated by generate_board.py; edit config/hardware.json.', '#pragma once', 'namespace aircheck::board {']
    lines += [f'constexpr unsigned {key} = {value};' for key, value in constants.items()]
    lines += ['}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    firmware = Path(__file__).resolve().parent
    config = json.loads((firmware.parents[1] / 'config/hardware.json').read_text(encoding='utf-8'))
    expected = render(config)
    output = firmware / 'src/board.hpp'
    if args.check:
        if not output.exists() or output.read_text(encoding='utf-8') != expected:
            raise SystemExit('board.hpp is stale; run firmware/esp32/generate_board.py')
    else:
        output.write_text(expected, encoding='utf-8')


if __name__ == '__main__':
    main()
